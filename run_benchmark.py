#!/usr/bin/env python3
"""
AgentCodec Paper Benchmark Runner

Usage:
    # Full benchmark (all techniques × all tasks, including standard benchmarks)
    python run_benchmark.py

    # Quick smoke test
    python run_benchmark.py --config configs/quick.yaml

    # Specific techniques only
    python run_benchmark.py --techniques baseline diversity_mrc harq_ir turbo

    # Custom models
    python run_benchmark.py --models gpt-4o-mini gpt-4o

    # Generate plots from existing results
    python run_benchmark.py --plot-only results/benchmark_20240101_120000.json

    # Use a different API endpoint (e.g., OpenRouter, local)
    python run_benchmark.py --base-url https://openrouter.ai/api/v1 --api-key $OPENROUTER_KEY
"""

import argparse
import logging
import sys
from collections import defaultdict
from pathlib import Path

import yaml

# Add project root to path
sys.path.insert(0, str(Path(__file__).parent))

# Use the library's vendored, zero-dependency .env loader instead of the
# external `python-dotenv` package, so the benchmark runner has one fewer
# install requirement. Importing agentcodec already auto-loads `.env`; the
# explicit call here is harmless and keeps intent obvious.
from agentcodec import load_dotenv

load_dotenv()  # loads .env file into os.environ

from agentcodec.plots import plot_all, plot_all_from_cache
from agentcodec.runner import BenchmarkRunner, ExperimentConfig
from benchmarks.tasks import get_all_tasks


def setup_logging(verbose: bool = False):
    level = logging.DEBUG if verbose else logging.INFO
    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)-7s | %(name)s | %(message)s",
        datefmt="%H:%M:%S",
    )


def load_config(config_path: str | None) -> dict:
    if config_path and Path(config_path).exists():
        with open(config_path) as f:
            return yaml.safe_load(f)
    return {}


def run_main_benchmark(args, cfg) -> list[dict]:
    """Run the main technique × task benchmark."""
    # Extract dataset options before passing to ExperimentConfig
    dataset_opts = {
        k: cfg.pop(k)
        for k in (
            "include_standard", "use_downloaded", "downloaded_n", "data_dir",
            "include_curated", "include_hard",
        )
        if k in cfg
    }
    # plot_dir is a runner/CLI concern, not an ExperimentConfig field — pop it
    # so ExperimentConfig(**cfg) doesn't raise on the unknown kwarg.
    plot_dir = cfg.pop("plot_dir", "plots")
    exp_config = ExperimentConfig(**cfg)

    logging.info("=" * 60)
    logging.info("PHASE 1: Main Benchmark")
    logging.info("=" * 60)
    logging.info(f"Models:     {[m['model'] for m in exp_config.models]}")
    logging.info(f"Judge:      {exp_config.judge_model}")
    logging.info(f"Techniques: {exp_config.techniques}")
    logging.info(f"Categories: {exp_config.categories}")
    logging.info("=" * 60)

    tasks = get_all_tasks(
        include_standard=dataset_opts.get("include_standard", True),
        use_downloaded=dataset_opts.get("use_downloaded", False),
        downloaded_n=dataset_opts.get("downloaded_n"),
        data_dir=dataset_opts.get("data_dir"),
        include_curated=dataset_opts.get("include_curated", True),
        include_hard=dataset_opts.get("include_hard", True),
        min_difficulty=exp_config.min_difficulty,
    )
    label = "downloaded" if dataset_opts.get("use_downloaded") else "curated + standard"
    logging.info(f"Loaded {len(tasks)} benchmark tasks ({label})")

    live_plots = not getattr(args, 'no_live_plots', False)
    Path(plot_dir).mkdir(parents=True, exist_ok=True)
    runner = BenchmarkRunner(exp_config)
    results = runner.run_all(tasks, live_plots=live_plots, plot_dir=plot_dir)

    # Generate final plots from the file just saved (not an arbitrary latest file)
    results_files = sorted(Path(exp_config.output_dir).glob("benchmark_*.json"))
    if results_files:
        latest = results_files[-1]
        # Verify it was generated by this run (within last 60 seconds)
        import time as _time
        if _time.time() - latest.stat().st_mtime < 60:
            plot_all(latest, output_dir=plot_dir)
        else:
            logging.warning(f"Latest results file {latest} is stale — skipping plot generation")

    return results


def main():
    parser = argparse.ArgumentParser(
        description="AgentCodec: Communication-Theoretic Reliability Benchmark"
    )
    parser.add_argument("--config", "-c", type=str, default="configs/default.yaml",
                        help="YAML config file path")
    parser.add_argument("--techniques", "-t", nargs="+",
                        help="Techniques to run (overrides config)")
    parser.add_argument("--categories", nargs="+",
                        help="Task categories to run (overrides config)")
    parser.add_argument("--models", "-m", nargs="+",
                        help="Models to use (overrides config)")
    parser.add_argument("--judge-model", type=str,
                        help="Model for quality scoring")
    parser.add_argument("--output-dir", "-o", type=str,
                        help="Output directory for results")
    parser.add_argument("--plot-dir", type=str,
                        help="Output directory for plots (overrides config plot_dir)")
    parser.add_argument("--base-url", type=str,
                        help="API base URL (for OpenRouter, local, etc.)")
    parser.add_argument("--api-key", type=str,
                        help="API key (defaults to OPENAI_API_KEY env var)")
    parser.add_argument("--plot-only", type=str,
                        help="Skip experiments, just generate plots from results file")
    parser.add_argument("--plot-from-cache", type=str,
                        help="Generate plots from a cache directory (e.g. results/cache)")
    parser.add_argument("--no-live-plots", action="store_true",
                        help="Disable live plot updates after each technique")
    parser.add_argument("--min-difficulty", type=str,
                        choices=["easy", "medium", "hard", "very_hard", "extreme"],
                        help="Minimum task difficulty (filters out easier tasks)")
    parser.add_argument("--parallel-tasks", type=int,
                        help="Number of (task, repeat) workers to run concurrently "
                             "within a single technique (default: 1 = sequential). "
                             "Overrides config.parallel_tasks.")
    parser.add_argument("--verbose", "-v", action="store_true",
                        help="Verbose logging")

    args = parser.parse_args()
    setup_logging(args.verbose)

    # Load config (also needed for plot-only modes so plot_dir is honored)
    cfg = load_config(args.config)
    plot_dir_for_plot_only = args.plot_dir or cfg.get("plot_dir", "plots")

    # Plot-only modes
    if args.plot_only:
        logging.info(f"Generating plots from {args.plot_only} → {plot_dir_for_plot_only}/")
        plot_all(args.plot_only, output_dir=plot_dir_for_plot_only)
        return
    if args.plot_from_cache:
        logging.info(
            f"Generating plots from cache directory {args.plot_from_cache} "
            f"→ {plot_dir_for_plot_only}/"
        )
        plot_all_from_cache(args.plot_from_cache, output_dir=plot_dir_for_plot_only)
        return

    # CLI overrides
    if args.techniques:
        cfg["techniques"] = args.techniques
    if args.categories:
        cfg["categories"] = args.categories
    if args.models:
        cfg["models"] = [{"model": m, "temperature": 0.7} for m in args.models]
    if args.judge_model:
        cfg["judge_model"] = args.judge_model
    if args.output_dir:
        cfg["output_dir"] = args.output_dir
    if args.plot_dir:
        cfg["plot_dir"] = args.plot_dir
    if args.base_url:
        cfg["base_url"] = args.base_url
    if args.api_key:
        cfg["api_key"] = args.api_key
    if getattr(args, 'judge_base_url', None):
        cfg["judge_base_url"] = args.judge_base_url
    if getattr(args, 'judge_api_key', None):
        cfg["judge_api_key"] = args.judge_api_key
    if getattr(args, 'min_difficulty', None):
        cfg["min_difficulty"] = args.min_difficulty
    if getattr(args, 'parallel_tasks', None) is not None:
        cfg["parallel_tasks"] = args.parallel_tasks

    results = run_main_benchmark(args, cfg)
    print_summary(results)


def print_summary(results: list[dict]):
    logging.info("\n" + "=" * 60)
    logging.info("SUMMARY")
    logging.info("=" * 60)
    total_cost = sum(r.get("total_cost_usd", 0) for r in results)
    total_runs = len(results)
    errors = sum(1 for r in results if "error" in r)
    logging.info(f"Total runs:  {total_runs}")
    logging.info(f"Errors:      {errors}")
    logging.info(f"Total cost:  ${total_cost:.4f}")

    by_tech = defaultdict(list)
    for r in results:
        if "error" not in r:
            by_tech[r["technique"]].append(r["final_quality"])

    logging.info(f"\n{'Technique':<25} {'Mean Quality':>12} {'Min':>6} {'Max':>6} {'N':>4}")
    logging.info("-" * 55)
    for tech in sorted(by_tech.keys()):
        quals = by_tech[tech]
        logging.info(
            f"{tech:<25} {sum(quals)/len(quals):>12.3f} {min(quals):>6.3f} {max(quals):>6.3f} {len(quals):>4}"
        )


if __name__ == "__main__":
    main()
